# ==================== MONGODB MODELS ====================

class PyObjectId(ObjectId):
    """Custom type for MongoDB ObjectId."""
    @classmethod
    def __get_validators__(cls):
        yield cls.validate

    @classmethod
    def validate(cls, v):
        if isinstance(v, ObjectId):
            return v
        if isinstance(v, str):
            return ObjectId(v)
        raise ValueError(f"Invalid ObjectId: {v}")

    def __repr__(self):
        return f"ObjectId('{self}')"


# ==================== INTERVIEW MODELS ====================

class EvaluationData(BaseModel):
    """Answer evaluation data generated by Gemini or heuristic fallback."""
    correctness: int = 0
    completeness: int = 0
    technical_depth: int = 0
    clarity: int = 0
    total_score: int = 0
    feedback: str = ""
    strengths: List[str] = Field(default_factory=list)
    weaknesses: List[str] = Field(default_factory=list)
    follow_up_needed: bool = False


class TranscriptItem(BaseModel):
    """One interview turn with evaluation."""
    question: str
    answer: str
    evaluation: EvaluationData


class InterviewReport(BaseModel):
    """Final interview report with overall assessment."""
    total_score: int = 0
    average_score: float = 0.0
    strengths: List[str] = Field(default_factory=list)
    weaknesses: List[str] = Field(default_factory=list)
    recommendations: List[str] = Field(default_factory=list)
    readiness_label: str = ""
    questions_asked: int = 0


class SessionData(BaseModel):
    """Enhanced session data model for AI interview flow."""
    session_id: str
    interview_type: str
    role: Optional[str] = None
    mode: str = "text"
    resume_filename: Optional[str] = None
    resume_summary: str = "NA"
    extracted_text: str = ""
    current_question: str = ""
    current_stage: str = "intro"
    questions_asked: int = 0
    max_questions: int = 6
    transcript: List[TranscriptItem] = Field(default_factory=list)
    topics_covered: List[str] = Field(default_factory=list)
    last_answer: str = ""
    last_question_type: str = ""
    status: str = "in_progress"
    is_finished: bool = False
    created_at: Optional[datetime] = None
    final_report: Optional[InterviewReport] = None


class StartRoleRequest(BaseModel):
    """Request model for starting role-based interview."""
    role: str
    mode: str = "text"
    max_questions: Optional[int] = 6
    user_id: Optional[str] = None


class StartResumeRequest(BaseModel):
    """Request model for starting resume-based interview."""
    resume_summary: Optional[str] = None
    mode: str = "text"
    max_questions: Optional[int] = 6


class AnswerRequest(BaseModel):
    """Request model for submitting an answer."""
    session_id: str
    answer: str


class EndInterviewRequest(BaseModel):
    """Request model for ending interview."""
    session_id: str


class SessionResponse(BaseModel):
    """Response model returning full session."""
    session: SessionData


class DeleteSessionResponse(BaseModel):
    success: bool
    message: str


class HealthResponse(BaseModel):
    status: str
    message: str


